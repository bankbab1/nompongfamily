const COPY: Record<Locale, Shape<PortalCopy>> = { th, en }

/** Fills {name} placeholders. */
export const fill = (text: string, vars: Record<string, string | number>) => text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))

export function copyFor(locale: Locale) {
  return COPY[locale]
}

/** Portal text in the visitor's language. */
export function useCopy() {
  return copyFor(useLocale())
}
